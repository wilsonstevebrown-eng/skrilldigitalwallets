/*
# Create owner-scoped wallet profiles

1. New database objects
- `customer_id_seq`: private sequence used to generate stable customer IDs.
- `profiles`: one profile row per authenticated account.
- `handle_new_user`: trigger function that creates a profile after registration.

2. New columns on `profiles`
- `id`: the authenticated user's ID and primary key.
- `display_name`: the name shown on the wallet dashboard.
- `email`: the account email address copied from authentication.
- `account_id`: a server-generated customer ID such as `BES000050`.
- `created_at` and `updated_at`: profile timestamps.

3. Security
- Row Level Security is enabled on `profiles`.
- Authenticated users can select, update, and delete only their own profile row.
- Profile creation is performed by the database trigger, not by the browser.
- Only `display_name` is writable by the authenticated client; identity, email, account ID, and timestamps are protected.
- Anonymous users cannot read or write profiles.

4. Important notes
- The trigger reads the optional display name supplied during sign-up and falls back to the email prefix.
- The account ID is generated by the database and cannot be chosen or changed by the user.
- The migration is idempotent and safe to apply again.
*/

CREATE SEQUENCE IF NOT EXISTS public.customer_id_seq START WITH 49;

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text NOT NULL,
  email text NOT NULL,
  account_id text NOT NULL UNIQUE DEFAULT ('BES' || lpad(nextval('public.customer_id_seq')::text, 6, '0')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name, email)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'display_name', ''), split_part(NEW.email, '@', 1)),
    NEW.email
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

DROP POLICY IF EXISTS "Users can view own profile" ON public.profiles;
CREATE POLICY "Users can view own profile"
  ON public.profiles FOR SELECT
  TO authenticated
  USING (auth.uid() = id);

DROP POLICY IF EXISTS "Users can create own profile" ON public.profiles;
CREATE POLICY "Users can create own profile"
  ON public.profiles FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile"
  ON public.profiles FOR UPDATE
  TO authenticated
  USING (auth.uid() = id)
  WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can delete own profile" ON public.profiles;
CREATE POLICY "Users can delete own profile"
  ON public.profiles FOR DELETE
  TO authenticated
  USING (auth.uid() = id);

REVOKE ALL ON TABLE public.profiles FROM anon;
REVOKE INSERT, DELETE ON TABLE public.profiles FROM authenticated;
REVOKE UPDATE ON TABLE public.profiles FROM authenticated;
GRANT SELECT ON TABLE public.profiles TO authenticated;
GRANT UPDATE (display_name) ON TABLE public.profiles TO authenticated;
REVOKE ALL ON SEQUENCE public.customer_id_seq FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
